"""Model II: central spin coupled to an interacting spin chain.

Because every term commutes with sigma_z^S, the evolution splits into two
sectors s = +-1 in which the bath evolves under H_E^s = H_E + s V, with
V = sum_j g_j sigma_z^j.  The decoherence factor is then the Loschmidt
echo r(t) = <E(0)| e^{i H_E^- t} e^{-i H_E^+ t} |E(0)>.
"""
import numpy as np

SX = np.array([[0, 1], [1, 0]], float)
SY = np.array([[0, -1j], [1j, 0]])
SZ = np.array([[1, 0], [0, -1]], float)
I2 = np.eye(2)


def op(single, site, N):
    """Embed a single-site operator at `site` of an N-qubit chain."""
    out = np.array([[1.0 + 0j]])
    for k in range(N):
        out = np.kron(out, single if k == site else I2)
    return out


def two(a, b, i, j, N):
    out = np.array([[1.0 + 0j]])
    for k in range(N):
        m = a if k == i else (b if k == j else I2)
        out = np.kron(out, m)
    return out


def bath_hamiltonian(N, J1=1.0, delta=1.0, J2=0.0, h=0.0):
    """XXZ chain with optional next-nearest-neighbour coupling."""
    H = np.zeros((2 ** N, 2 ** N), complex)
    for j in range(N - 1):
        H += J1 * (two(SX, SX, j, j + 1, N) + two(SY, SY, j, j + 1, N)
                   + delta * two(SZ, SZ, j, j + 1, N))
    for j in range(N - 2):
        H += J2 * (two(SX, SX, j, j + 2, N) + two(SY, SY, j, j + 2, N)
                   + delta * two(SZ, SZ, j, j + 2, N))
    if h:
        for j in range(N):
            H += h * op(SZ, j, N)
    return H


def coupling_operator(g):
    """V = sum_j g_j sigma_z^j, diagonal in the computational basis."""
    N = len(g)
    diag = np.zeros(2 ** N)
    for j, gj in enumerate(g):
        bit = (np.arange(2 ** N) >> (N - 1 - j)) & 1
        diag += gj * (1 - 2 * bit)
    return diag


def branches(N, g, times, J1=1.0, delta=1.0, J2=0.0, h=0.0):
    """Conditional bath states and the which-path echo trajectory."""
    HE = bath_hamiltonian(N, J1, delta, J2, h)
    V = np.diag(coupling_operator(g))
    psi0 = np.ones(2 ** N, complex) / 2 ** (N / 2)
    out = {}
    eig = {}
    for s in (+1, -1):
        w, U = np.linalg.eigh(HE + s * V)
        eig[s] = (w, U)
        c = U.conj().T @ psi0
        out[s] = (U * c) @ np.exp(-1j * np.outer(times, w)).T
        out[s] = np.einsum("ik,tk->ti", U * c, np.exp(-1j * np.outer(times, w)))
    wm, Um = eig[-1]
    d = Um.conj().T @ out[+1].T
    echo = np.einsum("ik,tk->ti", Um, (np.exp(1j * np.outer(times, wm)) * d.T))
    return out[+1], out[-1], echo


def h2(p):
    p = np.clip(np.asarray(p, float), 1e-15, 1 - 1e-15)
    return -p * np.log2(p) - (1 - p) * np.log2(1 - p)


def channels_model2(N, g, times, frag=2, **kw):
    """Record, coherence, and dynamically generated future channels."""
    Ep, Em, chi = branches(N, g, times, **kw)
    r = np.einsum("ti,ti->t", Em.conj(), Ep)
    S_S = h2((1 + np.abs(r)) / 2)
    I_pres = 1.0 - S_S

    nf = N // frag
    I_past = np.zeros(len(times))
    rest0 = list(range(frag, N))
    for f in range(nf):
        keep = list(range(f * frag, (f + 1) * frag))
        rest = [k for k in range(N) if k not in keep]
        perm = keep + rest
        dF, dR = 2 ** frag, 2 ** len(rest)
        A_all = np.transpose(Ep.reshape([-1] + [2] * N),
                             [0] + [q + 1 for q in perm]).reshape(-1, dF, dR)
        B_all = np.transpose(Em.reshape([-1] + [2] * N),
                             [0] + [q + 1 for q in perm]).reshape(-1, dF, dR)
        for ti in range(len(times)):
            A, B = A_all[ti], B_all[ti]
            rho_p, rho_m = A @ A.conj().T, B @ B.conj().T
            rho_F = 0.5 * (rho_p + rho_m)
            off = 0.5 * (A @ B.conj().T)
            rho_SF = np.block([[0.5 * rho_p, off], [off.conj().T, 0.5 * rho_m]])

            def S(rho):
                w = np.linalg.eigvalsh(rho)
                w = w[w > 1e-13]
                return float(-(w * np.log2(w)).sum())

            I_past[ti] += S_S[ti] + S(rho_F) - S(rho_SF)

    # future channel: entropy of the time-averaged echo state,
    # rho_bar(t) = (1/t) int_0^t |chi(t')><chi(t')| dt'.  The echo
    # trajectory is generated by the difference of the two branch
    # Hamiltonians, so it is the which-path motion alone.
    dH = np.sqrt((np.asarray(g) ** 2).sum())
    tau_MT = np.pi / (2 * dH)
    I_fut = np.zeros(len(times))
    for ti in range(1, len(times)):
        M = chi[:ti + 1]
        wts = np.gradient(times[:ti + 1])
        wts = wts / wts.sum()
        G = (M.conj() * wts[:, None]) @ M.T
        w = np.linalg.eigvalsh(G)
        w = w[w > 1e-12]
        I_fut[ti] = float(-(w * np.log2(w)).sum())

    return dict(t=times, r=r, coherence=0.5 * np.abs(r), I_past=I_past,
                I_present=I_pres, I_future=I_fut,
                I_total=I_past + I_pres + I_fut,
                dH=dH, T2=1.0 / (np.sqrt(2) * dH), tau_MT=tau_MT)
